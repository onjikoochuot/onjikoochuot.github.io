// Writes the market list the server scans, from the app's CATALOG (single source of truth).
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
execSync(`app/node_modules/.bin/esbuild scripts/catalog-entry.ts --bundle --platform=node --log-level=error --outfile=/tmp/viko-cat.cjs`);
const { CATALOG } = await import("/tmp/viko-cat.cjs");
const rows = CATALOG.map((c) => [c.id, c.label, c.market]);
writeFileSync("supabase/functions/_shared/universe.ts", `// Generated by scripts/gen-universe.mjs from app/src/lib/api.ts. Do not edit by hand.\nexport const UNIVERSE: [string, string, string][] = ${JSON.stringify(rows)};\n`);
console.log(`universe: ${rows.length} markets`);
